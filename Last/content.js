window.DATA = DATA;


function openCatalogByName(name) {
    const cats = document.querySelectorAll(".category-name p");
    for (let c of cats) {
        if (c.innerText.trim() === name.trim()) {
            const clickable = c.closest(".category");
            if (clickable) {
                clickable.click();
                console.log("📂 فتح الكتالوج:", name);
                return true;
            }
        }
    }
    console.log("❌ الكتالوج مش موجود:", name);
    return false;
}


function disableItem(itemName) {
    const items = document.querySelectorAll(".item-name");

    for (let item of items) {
        if (item.innerText.trim() === itemName.trim()) {

            console.log("🔎 موجود:", itemName);

            const header = item.closest("mat-expansion-panel-header");
            if (!header) {
                console.log("⚠️ لم أجد header للصنف:", itemName);
                continue;
            }


            const input = header.querySelector('input.mat-slide-toggle-input, input[role="switch"], input[type="checkbox"]');

            if (input) {
                const aria = input.getAttribute('aria-checked');
                if (aria === 'false' || input.checked === false) {
                    console.log("ℹ️ الحالة aria-checked='false' أو checked=false — لن يتم أي إجراء على:", itemName);
                    return;
                }
            } else {
                console.log("⚠️ لم أجد input داخل toggle، سأحاول النقر على عنصر الـ toggle المضيف إذا وجد.");
            }

            const toggleHost = header.querySelector("mat-slide-toggle") || header.querySelector(".mat-slide-toggle");
            if (!toggleHost) {
                console.log("⚠️ لم أجد toggle host للصنف:", itemName);
                continue;
            }

            toggleHost.click();

            setTimeout(() => {
                const options = document.querySelectorAll(".availability-cta p");

                for (let opt of options) {
                    if (opt.innerText.includes("غير متوفر اليوم")) {
                        opt.click();
                        console.log("⭕ تم إيقاف:", itemName);
                        return;
                    }
                }
                console.log("⚠️ لم أجد خيار 'غير متوفر اليوم' للصنف:", itemName);
            }, 700);

            return;
        }
    }

    console.log("❌ الصنف مش موجود:", itemName);
}


