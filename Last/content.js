window.startAutoDisable = async function (dataKey) {
    try {
        const key = dataKey || Object.keys(DATA)[0];
        if (!DATA[key]) {
            console.error("❌ المفتاح غير موجود في DATA:", key);
            return;
        }

        const catalogList = DATA[key].catalogs;

        for (let catalogName in catalogList) {

            const items = catalogList[catalogName];

            openCatalogByName(catalogName);

            await new Promise(s => setTimeout(s, 1200));

            for (let itemName of items) {
                disableItem(itemName);
                await new Promise(s => setTimeout(s, 1500));
            }
        }

        console.log("✔✔✔ تم إيقاف كل الأصناف المطلوبة لمجموعة:", key);
    } catch (err) {
        console.error("خطأ أثناء التشغيل:", err);
    }
};